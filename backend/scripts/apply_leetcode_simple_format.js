function getCompanies(no, topic) {
  const seed = (no * 17 + topic.length * 13) % COMPANY_POOL.length;
  const count = 3 + (no % 3);
  const result = [];
  for (let i = 0; i < count; i++) {
    const comp = COMPANY_POOL[(seed + i * 3) % COMPANY_POOL.length];
    if (!result.includes(comp)) result.push(comp);
  }
  return result;
}

function cleanTitleString(str) {
  if (!str) return 'Algorithmic Problem';
  let s = str
    .replace(/^###\s*problem\s*(statement|description)\s*/gi, '')
    .replace(/###\s*problem\s*(statement|description)\s*/gi, '')
    .replace(/###\s*input\s*format\s*/gi, '')
    .replace(/^read\s+/i, '')
    .replace(/^check\s+whether\s+/i, 'Check ')
    .replace(/^check\s+if\s+/i, 'Check ')
    .replace(/^find\s+the\s+/i, '')
    .replace(/^find\s+/i, '')
    .replace(/^print\s+the\s+/i, 'Print ')
    .replace(/^print\s+/i, 'Print ')
    .replace(/^determine\s+if\s+/i, 'Check ')
    .replace(/^count\s+the\s+/i, 'Count ')
    .replace(/^count\s+/i, 'Count ')
    .replace(/\s+under\s+strict\s+constraints\.?/gi, '')
    .replace(/\s*\(variant\s+\d+\)/gi, '')
    .replace(/\r?\n.*/g, '') // Keep first sentence only
    .trim();

  if (s.endsWith('.')) s = s.slice(0, -1);

  // Capitalize title
  const words = s.split(/\s+/);
  return words.map((w, idx) => {
    const lower = w.toLowerCase();
    if (idx > 0 && ['and', 'or', 'of', 'in', 'on', 'at', 'to', 'for', 'with', 'a', 'an', 'the'].includes(lower)) {
      return lower;
    }
    return w.charAt(0).toUpperCase() + w.slice(1);
  }).join(' ');
}

