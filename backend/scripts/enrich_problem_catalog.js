function formatTitle(raw) {
  if (!raw) return 'Algorithmic Problem';
  let t = raw
    .replace(/^read\s+/i, '')
    .replace(/^check\s+whether\s+/i, 'Check ')
    .replace(/^check\s+if\s+/i, 'Check ')
    .replace(/^find\s+the\s+/i, '')
    .replace(/^find\s+/i, '')
    .replace(/^print\s+the\s+/i, 'Print ')
    .replace(/^print\s+/i, 'Print ')
    .replace(/^determine\s+if\s+/i, 'Check ')
    .replace(/^count\s+the\s+/i, 'Count ')
    .replace(/^count\s+/i, 'Count ')
    .replace(/\s+under\s+strict\s+constraints\.?/i, '')
    .replace(/\s*\(variant\s+\d+\)/i, '')
    .trim();

  // Remove trailing period
  if (t.endsWith('.')) t = t.slice(0, -1);

  // Capitalize each word properly
  return t
    .split(' ')
    .map((word, idx) => {
      const lower = word.toLowerCase();
      if (idx > 0 && ['and', 'or', 'of', 'in', 'on', 'at', 'to', 'for', 'with', 'a', 'an', 'the'].includes(lower)) {
        return lower;
      }
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(' ');
}

